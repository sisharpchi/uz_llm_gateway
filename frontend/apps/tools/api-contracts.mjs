import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const check = process.argv.includes('--check');
const env = { ...process.env, ASPNETCORE_ENVIRONMENT: 'Development', DOTNET_ENVIRONMENT: 'Development',
  APIKEYS__FINGERPRINTKEY: randomBytes(32).toString('base64'),
  PROVIDERSECRETS__ACTIVEKEYVERSION: 'docs', PROVIDERSECRETS__KEYS__docs: randomBytes(32).toString('base64'),
  ConnectionStrings__Postgres: 'Host=127.0.0.1;Port=1;Database=docs;Username=docs',
  ConnectionStrings__Redis: '127.0.0.1:1,connectTimeout=10',
  DataProtection__KeyRingPath: '', DataProtection__CertificatePath: '', DataProtection__CertificatePassword: '' };

export function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === 'object') return Object.fromEntries(
    Object.keys(value).sort().map(key => [key, canonicalize(value[key])]));
  return value;
}

export function artifactMatches(expected, actual) {
  return expected.replace(/\r\n/g, '\n') === actual.replace(/\r\n/g, '\n');
}

function artifact(path, content) {
  const target = resolve(root, path);
  if (check) {
    let existing;
    try { existing = readFileSync(target, 'utf8'); } catch { existing = ''; }
    if (!artifactMatches(content, existing)) throw new Error(`Contract drift: ${path}. Run npm run api:generate --prefix frontend/apps and review the API/client changes.`);
  } else {
    mkdirSync(resolve(target, '..'), { recursive: true });
    writeFileSync(target, content);
  }
}

export async function generate() {
  for (const [host, name] of [['UZLLM.Gateway.Api', 'gateway'], ['UZLLM.Management.Api', 'management']]) {
    const build = spawnSync('dotnet', ['build', `src/${host}/${host}.csproj`, '--configuration', 'Release',
      '-p:OpenApiGenerateDocumentsOnBuild=true', `-p:OpenApiDocumentsDirectory=${resolve(root, 'artifacts/openapi')}`,
      '--no-incremental', '--nologo', '-v:q'], { cwd: root, env, encoding: 'utf8', timeout: 180_000 });
    if (build.status !== 0) throw new Error(`${host} OpenAPI generation failed: ${build.error ?? ''}\n${build.stdout}\n${build.stderr}`);
    const document = canonicalize(JSON.parse(readFileSync(resolve(root, `artifacts/openapi/${name}-v1.json`), 'utf8')));
    artifact(`docs/api/${name}-v1.openapi.json`, JSON.stringify(document, null, 2) + '\n');
    const ast = await openapiTS(document, { alphabetize: true });
    artifact(`frontend/packages/api-client/generated/${name}-v1.ts`,
      '// Generated by npm run api:generate. Do not edit; review the versioned OpenAPI source.\n' + astToString(ast));
    console.log(`${name} v1 OpenAPI and TypeScript ${check ? 'match' : 'generated'}`);
  }
  const fixtures = spawnSync('dotnet', ['test', 'tests/Contract/UZLLM.Gateway.ContractTests/UZLLM.Gateway.ContractTests.csproj',
    '--configuration', 'Release', '--filter', 'FullyQualifiedName~OpenApiWireContractTests', '--nologo', '-v:q'],
    { cwd: root, env, encoding: 'utf8', timeout: 180_000 });
  if (fixtures.status !== 0) throw new Error(`Wire fixture generation failed:\n${fixtures.stdout}\n${fixtures.stderr}`);
  artifact('docs/api/examples.json', JSON.stringify(canonicalize(JSON.parse(
    readFileSync(resolve(root, 'artifacts/contracts/dx002-wire.json'), 'utf8'))), null, 2) + '\n');
  console.log(`Serializer-derived examples ${check ? 'match' : 'generated'}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generate();
